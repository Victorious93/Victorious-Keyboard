"""
Generates the Victorious Keyboard logo from one geometry description:

  * app/src/main/res/drawable/ic_app_icon_{stable,debug}_{foreground,monochrome}.xml   (Android VectorDrawable)
  * docs/branding/logo.svg, logo_debug.svg                                             (master art, with background)

Original artwork: a hooded figure with a neon-edged face and a red-glowing laptop carrying the "V" mark. It is
inspired by the mood of a reference wallpaper but copies none of its artwork.

Usage (pure standard library):  python3 -I docs/branding/make_logo.py
Raster files (play_store_icon_512.png, preview_masks.png) are rendered from the SVG separately, see README.md.

Geometry is drawn on the 108x108 adaptive-icon canvas. Everything important stays inside the 66dp safe-zone circle
(radius 33 around 54,54); the script asserts that for the sampled outline points.
"""
import math, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res", "drawable")
OUT = os.path.dirname(os.path.abspath(__file__))
BACKGROUND = "#11151C"  # = @color/ic_app_icon_background

HOOD = ("M54,22 C45,22 38.5,28.5 38,38 C37.6,45 36,51 32,56 C28.5,60.5 27.5,67 29.5,74 L78.5,74 "
        "C80.5,67 79.5,60.5 76,56 C72,51 70.4,45 70,38 C69.5,28.5 63,22 54,22 Z")
HOOD_FOLD = "M43.5,34 C44.5,27.5 49,24.5 54,24.5 C59,24.5 63.5,27.5 64.5,34"
FACE = ("M45.5,36 L62.5,36 C64.2,36 65,36.8 65,38.5 L65,50 C65,53.5 62.5,56 59,57.5 L54,59.5 L49,57.5 "
        "C45.5,56 43,53.5 43,50 L43,38.5 C43,36.8 43.8,36 45.5,36 Z")
EYE_L = "M46.5,41 L50.5,44 L46.5,47"
EYE_R = "M56.5,47.5 L61.5,47.5"
SMILE = "M47,52 Q54,55.5 61,52"
TICKS = [f"M{47 + 14 * t:.1f},{52 + 7 * t * (1 - t) - 1.3:.2f} L{47 + 14 * t:.1f},{52 + 7 * t * (1 - t) + 1.3:.2f}"
         for t in (0.1, 0.3, 0.5, 0.7, 0.9)]
LID = "M37,74 L37,65 C37,63.5 38,62.5 39.5,62.5 L68.5,62.5 C70,62.5 71,63.5 71,65 L71,74"
LID_HOLE = "M38.7,74 L38.7,65.2 C38.7,64.5 39.2,64 40,64 L68,64 C68.8,64 69.3,64.5 69.3,65.2 L69.3,74 Z"
V_MARK = "M50.2,66.2 L54,71.8 L57.8,66.2"

PALETTES = {
    "stable": {"accent": "#22D3EE", "glow": "#22D3EE", "laptop": "#F43F5E"},
    "debug": {"accent": "#FBBF24", "glow": "#FBBF24", "laptop": "#F43F5E"},  # amber = "this is the debug build"
}


def stroke(d, color, w, alpha=1.0):
    return dict(d=d, stroke=color, sw=w, alpha=alpha)


def glow(d, color, w):
    """Neon look without blur filters (VectorDrawable has none): wide translucent strokes under a crisp one."""
    return [stroke(d, color, w * 4.2, 0.07), stroke(d, color, w * 2.6, 0.14), stroke(d, color, w, 1.0)]


def color_layers(p):
    L = [dict(d=HOOD, fill="#1A2230")]
    L += [stroke(HOOD, p["glow"], 3.6, 0.10), stroke(HOOD, p["accent"], 0.8, 0.55)]
    L += [stroke(HOOD_FOLD, p["accent"], 0.7, 0.35)]
    L += [dict(d=FACE, fill="#04070B")]
    L += glow(FACE, p["accent"], 1.0)
    for d in (EYE_L, EYE_R):
        L += glow(d, p["accent"], 1.5)
    L += glow(SMILE, p["accent"], 0.8)
    for d in TICKS:
        L += [stroke(d, p["accent"], 0.8)]
    L += glow(LID, p["laptop"], 1.3)
    L += glow(V_MARK, p["laptop"], 1.7)
    return L


def mono_layers():
    # One colour; the launcher tints the alpha channel. Face and lid interior are holes (even-odd) in the hood.
    return [
        dict(d=f"{HOOD} {FACE} {LID_HOLE}", fill="#000000", evenodd=True),
        stroke(EYE_L, "#000000", 1.7), stroke(EYE_R, "#000000", 1.7), stroke(SMILE, "#000000", 1.0),
        *[stroke(d, "#000000", 1.0) for d in TICKS],
        stroke(V_MARK, "#000000", 1.9),
    ]


def hex_to_android(c, alpha=1.0):
    return "#" + format(round(alpha * 255), "02X") + c[1:].upper() if alpha < 1 else "#FF" + c[1:].upper()


def to_vector(layers, comment):
    out = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {comment} Generated by docs/branding/make_logo.py; do not edit by hand. -->",
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"', '    android:width="108dp"',
           '    android:height="108dp"', '    android:viewportWidth="108"', '    android:viewportHeight="108">']
    for l in layers:
        a = ['  <path', f'      android:pathData="{l["d"]}"']
        if "fill" in l:
            a.append(f'      android:fillColor="{hex_to_android(l["fill"])}"')
            if l.get("evenodd"):
                a.append('      android:fillType="evenOdd"')
        else:
            a += [f'      android:strokeColor="{hex_to_android(l["stroke"])}"', f'      android:strokeWidth="{l["sw"]:g}"',
                  '      android:strokeLineCap="round"', '      android:strokeLineJoin="round"']
            if l["alpha"] < 1:
                a.append(f'      android:strokeAlpha="{l["alpha"]:g}"')
        out.append("\n".join(a) + " />")
    out.append("</vector>")
    return "\n".join(out) + "\n"


def to_svg(layers, with_background=True):
    parts = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">']
    if with_background:
        parts.append(f'  <rect width="108" height="108" fill="{BACKGROUND}"/>')
    for l in layers:
        if "fill" in l:
            rule = ' fill-rule="evenodd"' if l.get("evenodd") else ""
            parts.append(f'  <path d="{l["d"]}" fill="{l["fill"]}"{rule}/>')
        else:
            op = f' stroke-opacity="{l["alpha"]:g}"' if l["alpha"] < 1 else ""
            parts.append(f'  <path d="{l["d"]}" fill="none" stroke="{l["stroke"]}" stroke-width="{l["sw"]:g}" '
                         f'stroke-linecap="round" stroke-linejoin="round"{op}/>')
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def check_safe_zone():
    """Sample the key outlines (cubic/quadratic Béziers included) and require them inside the 33dp safe radius."""
    worst = 0.0
    for d in (HOOD, LID):
        nums = [float(x) for x in re.findall(r"-?\d+\.?\d*", d)]
        pts = list(zip(nums[0::2], nums[1::2]))  # control points only: a conservative bound
        for x, y in pts:
            worst = max(worst, math.hypot(x - 54, y - 54))
    assert worst <= 33.5, f"content leaves the safe zone: {worst:.1f}dp"
    return worst


def main():
    worst = check_safe_zone()
    for variant, p in PALETTES.items():
        fg = color_layers(p)
        with open(os.path.join(RES, f"ic_app_icon_{variant}_foreground.xml"), "w") as f:
            f.write(to_vector(fg, f"Victorious Keyboard logo ({variant}): hooded figure, neon face, red laptop with the V mark."))
        with open(os.path.join(RES, f"ic_app_icon_{variant}_monochrome.xml"), "w") as f:
            f.write(to_vector(mono_layers(), f"Victorious Keyboard logo ({variant}), themed/monochrome variant."))
        name = "logo.svg" if variant == "stable" else "logo_debug.svg"
        with open(os.path.join(OUT, name), "w") as f:
            f.write(to_svg(fg))
    print(f"ok; farthest outline control point from centre: {worst:.1f}dp (safe zone 33dp)")


if __name__ == "__main__":
    sys.exit(main())
